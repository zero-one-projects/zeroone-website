const { test } = require('node:test');
const assert = require('node:assert/strict');
test('client record API authenticates, separates client types, and shows linked billing', { skip: process.env.RUN_CLIENT_DB_TESTS !== 'true' }, async () => {
  require('dotenv').config({ path: require('path').resolve(__dirname, '../../.env') });
  const { sequelize } = require('../config/database'); sequelize.options.logging = false;
  const { Quotation, BillingStatement, Client } = require('../models');
  const rows = [], createdClients = []; let server;
  const name = `Client record test ${require('crypto').randomUUID()}`;
  try {
    for (const type of ['subscription', 'project', 'pos']) rows.push(await Quotation.create({ document: { quoteType: type, clientName: name, clientEmail: 'client-record-test@example.test', title: `${type} test project`, currency: 'PHP', total: 1000 } }, { logging: false }));
    const bill = await BillingStatement.create({ quotationId: rows[0].id, period: '2026-10', document: { clientName: name, total: 1000, currency: 'PHP', dueOn: '2026-10-31' } }, { logging: false });
    server = await new Promise(resolve => { const instance = require('../app').listen(0, '127.0.0.1', () => resolve(instance)); });
    const base = `http://127.0.0.1:${server.address().port}/api/admin/clients`;
    const headers = { Authorization: `Bearer ${require('jsonwebtoken').sign({ sub: 'client-record-test', role: 1 }, process.env.JWT_SECRET, { expiresIn: '2m' })}` };
    assert.equal((await fetch(base)).status, 401);
    assert.equal((await fetch(`${base}?type=pos`, { headers })).status, 400);
    const listed = await (await fetch(`${base}?type=subscription&search=${encodeURIComponent(name)}`, { headers })).json();
    assert.equal(listed.total, 1); assert.equal(listed.clients[0].quotationCount, 1);
    const detail = await (await fetch(`${base}/${listed.clients[0].id}?type=subscription`, { headers })).json();
    assert.equal(detail.client.quotations[0].id, rows[0].id); assert.equal(detail.statements[0].id, bill.id);
    assert.equal((await fetch(`${base}/${listed.clients[0].id}?type=project`, { headers })).status, 404);
    const projects = await (await fetch(`${base}?type=project&search=${encodeURIComponent(name)}`, { headers })).json();
    assert.equal(projects.total, 1); assert.notEqual(projects.clients[0].id, listed.clients[0].id);
    const manualName = `${name} manually added`;
    const create = (body, auth = true) => fetch(base, { method: 'POST', headers: { ...(auth ? headers : {}), 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    const input = { type: 'subscription', clientName: manualName, clientEmail: 'manual-client@example.test', contactPerson: 'Test contact', clientAddress: 'Test address' };
    assert.equal((await create(input, false)).status, 401);
    assert.equal((await create({ ...input, clientEmail: 'invalid' })).status, 400);
    assert.equal((await create({ ...input, type: 'pos' })).status, 400);
    const created = await create(input); assert.equal(created.status, 201);
    const saved = (await created.json()).client; createdClients.push(saved.id);
    assert.equal((await create({ ...input, clientName: ` ${manualName.toUpperCase()} `, clientEmail: 'MANUAL-CLIENT@example.test' })).status, 409);
    const standalone = await (await fetch(`${base}/${saved.id}?type=subscription`, { headers })).json();
    assert.equal(standalone.client.clientName, manualName); assert.equal(standalone.client.quotations.length, 0); assert.equal(standalone.statements.length, 0);
    const standaloneList = await (await fetch(`${base}?type=subscription&search=${encodeURIComponent(manualName)}`, { headers })).json();
    assert.equal(standaloneList.total, 1); assert.equal(standaloneList.clients[0].quotationCount, 0);
    const project = await create({ ...input, type: 'project' }); assert.equal(project.status, 201);
    createdClients.push((await project.json()).client.id);
    assert.notEqual(createdClients[0], createdClients[1]);
    rows.push(await Quotation.create({ document: { quoteType: 'subscription', clientName: manualName, clientEmail: input.clientEmail, title: 'Matching later quotation', currency: 'PHP', total: 1000 } }, { logging: false }));
    const merged = await (await fetch(`${base}?type=subscription&search=${encodeURIComponent(manualName)}`, { headers })).json();
    assert.equal(merged.total, 1); assert.equal(merged.clients[0].quotationCount, 1); assert.equal(merged.clients[0].id, saved.id);
    assert.equal(saved.isActive, true);
    const changeStatus = (id, body, auth = true) => fetch(`${base}/${id}/status`, { method: 'PATCH', headers: { ...(auth ? headers : {}), 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    assert.equal((await changeStatus(saved.id, { type: 'subscription', isActive: false }, false)).status, 401);
    assert.equal((await changeStatus(saved.id, { type: 'subscription', isActive: 'false' })).status, 400);
    assert.equal((await changeStatus(saved.id, { type: 'project', isActive: false })).status, 404);
    assert.equal((await changeStatus(saved.id, { type: 'subscription', isActive: false })).status, 200);
    assert.equal((await Client.findByPk(saved.id, { logging: false })).isActive, false);
    const filtered = status => fetch(`${base}?type=subscription&search=${encodeURIComponent(manualName)}&status=${status}`, { headers }).then(response => response.json());
    assert.equal((await filtered('active')).total, 0);
    assert.equal((await filtered('inactive')).total, 1);
    assert.equal((await filtered('all')).total, 1);
    assert.equal((await create(input)).status, 409);
    const inactiveProfile = await (await fetch(`${base}/${saved.id}?type=subscription`, { headers })).json();
    assert.equal(inactiveProfile.client.isActive, false);
    const unaffectedProject = await (await fetch(`${base}/${createdClients[1]}?type=project`, { headers })).json(); assert.equal(unaffectedProject.client.isActive, true);
    assert.equal((await changeStatus(saved.id, { type: 'subscription', isActive: true })).status, 200);
    assert.equal((await filtered('active')).total, 1);
    const derivedId = listed.clients[0].id;
    assert.equal((await changeStatus(derivedId, { type: 'subscription', isActive: false })).status, 200); createdClients.push(derivedId);
    const derived = await (await fetch(`${base}/${derivedId}?type=subscription`, { headers })).json();
    assert.equal(derived.client.isActive, false); assert.equal(derived.client.quotations.length, 1);
  } finally {
    if (createdClients.length) await Client.destroy({ where: { id: createdClients }, logging: false });
    if (rows.length) { await BillingStatement.destroy({ where: { quotationId: rows.map(row => row.id) }, logging: false }); for (const row of rows) await row.destroy({ force: true, logging: false }); }
    if (server) await new Promise(resolve => server.close(resolve));
    await sequelize.close();
  }
});
